// Packs screen/ into the app: copies each file to packed/ as a Metro asset (.udra) and writes webfiles.js.
// Run automatically by `npm start`; the dev server re-runs it after every edit.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const WEB = path.join(ROOT, 'screen');
const OUT = path.join(ROOT, 'packed');

function walk(dir, base = '') {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => !e.name.startsWith('.'))
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name), base + e.name + '/') : [base + e.name]));
}

function pack() {
  fs.mkdirSync(OUT, { recursive: true });
  const hash = crypto.createHash('sha1');
  const lines = [];
  const keep = new Set();
  for (const rel of walk(WEB)) {
    const data = fs.readFileSync(path.join(WEB, rel));
    hash.update(rel).update(data);
    const flat = rel.replace(/\//g, '__').replace(/\./g, '_') + '.udra';
    keep.add(flat);
    const dest = path.join(OUT, flat);
    // Only touch files that changed, so Metro doesn't re-hash the 28 MB model on every edit.
    if (!fs.existsSync(dest) || !fs.readFileSync(dest).equals(data)) fs.writeFileSync(dest, data);
    lines.push(`  ['${rel}', require('./packed/${flat}')],`);
  }
  for (const f of fs.readdirSync(OUT)) if (!keep.has(f)) fs.unlinkSync(path.join(OUT, f));
  const version = hash.digest('hex').slice(0, 12);
  const js = '// Generated by scripts/pack.js from screen/. Do not edit.\n'
    + `export const WEB_VERSION = '${version}';\n`
    + 'export const WEB_FILES = [\n' + lines.join('\n') + '\n];\n';
  const target = path.join(ROOT, 'webfiles.js');
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== js) fs.writeFileSync(target, js);
  return version;
}

module.exports = pack;
if (require.main === module) console.log('Packed screen/ (version ' + pack() + ')');
